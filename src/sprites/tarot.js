// Polígonos trazados directamente por centro de píxel, sin antialiasing.
function mancha(ctx, color, puntos) {
  const vertices = puntos.split(' ').map(punto => punto.split(',').map(Number));
  ctx.fillStyle = color;
  for (let y = 3; y < 69; y++) {
    const cruces = [];
    for (let i = 0; i < vertices.length; i++) {
      const [x1, y1] = vertices[i];
      const [x2, y2] = vertices[(i + 1) % vertices.length];
      if ((y1 > y + .5) === (y2 > y + .5)) continue;
      cruces.push(x1 + (y + .5 - y1) * (x2 - x1) / (y2 - y1));
    }
    cruces.sort((a, b) => a - b);
    for (let i = 0; i < cruces.length; i += 2) {
      const x = Math.ceil(cruces[i] - .5);
      ctx.fillRect(x, y, Math.ceil(cruces[i + 1] - .5) - x, 1);
    }
  }
}

