export function ilustrarArcano(id, invertida) {
  const raster = superficie(48, 72);
  const ctx = raster.getContext('2d');
  pintarMarco(ctx, 48, 72, tinta, lino);
  escenas[id]((color, puntos) => mancha(ctx, color, puntos), (color, x, y, w, h) => {
    ctx.fillStyle = color;
    ctx.fillRect(x, y, w, h);
  });
  if (!invertida) return raster;
  const salida = superficie(48, 72);
  const invertido = salida.getContext('2d');
  invertido.translate(48, 72);
  invertido.scale(-1, -1);
  invertido.imageSmoothingEnabled = false;
  invertido.drawImage(raster, 0, 0);
  return salida;
}
